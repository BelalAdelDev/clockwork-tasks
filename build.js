// node build.js  ->  main.js (single-file CommonJS bundle; `obsidian` stays external)
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "src");
const mods = fs.readdirSync(dir).filter((f) => f.endsWith(".js"));
let out = `/* Clockwork Tasks - generated by build.js. Edit src/*.js instead. */\n"use strict";\nconst __defs = {\n`;
for (const f of mods) {
  const key = f.replace(/\.js$/, "");
  out += `${JSON.stringify(key)}: function (module, exports, require) {\n${fs.readFileSync(path.join(dir, f), "utf8")}\n},\n`;
}
out += `};
const __cache = {};
function __load(name) {
  if (__cache[name]) return __cache[name].exports;
  const module = (__cache[name] = { exports: {} });
  __defs[name](module, module.exports, (req) => {
    if (req.startsWith(".")) return __load(req.replace(/^\\.\\//, "").replace(/\\.js$/, ""));
    return require(req); // obsidian (and moment, only if window.moment is missing)
  });
  return module.exports;
}
module.exports = __load("main");
`;
fs.writeFileSync(path.join(__dirname, "main.js"), out);
console.log("built main.js", out.length, "bytes");
